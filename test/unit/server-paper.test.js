const test=require("node:test"),assert=require("node:assert/strict");
const {randomUUID}=require("node:crypto");
const {paperConfig}=require("../../src/paper/config");
const {createPaperService}=require("../../src/paper/service");
const {fixtureMarket,MINTS}=require("../fixtures/market");
const {isValid}=require("../../src/api/validation");
const command=fields=>({requestId:randomUUID(),createdAt:new Date().toISOString(),...fields});
test("server accounts default off and cannot activate with incomplete or insecure configuration",()=>{
  assert.deepEqual(paperConfig({}),{enabled:false});
  assert.throws(()=>paperConfig({PAPER_ACCOUNTS_ENABLED:"true"}),/DATABASE_URL/);
  const env={PAPER_ACCOUNTS_ENABLED:"true",DATABASE_URL:"fixture",GITHUB_CLIENT_ID:"fixture",GITHUB_CLIENT_SECRET:"fixture",PAPER_GITHUB_USER_ID:"123",PUBLIC_ORIGIN:"https://example.com"};
  assert.equal(paperConfig(env).enabled,true);
  for(const PUBLIC_ORIGIN of ["http://example.com","https://example.com/","garbage"])assert.throws(()=>paperConfig({...env,PUBLIC_ORIGIN}));
});
test("paper API does not accept client ownership, quotes, ledger writes or live mode",()=>{
  const body=command({type:"buy",mint:MINTS[0],amount:1,automatic:false,feed:"recent"});
  assert.equal(isValid("paperCommand",body),true);
  for(const extra of [{accountId:"other"},{userId:"other"},{executionMode:"live"},{priceUsd:1},{ledger:{}},{transaction:{}}])assert.equal(isValid("paperCommand",{...body,...extra}),false);
  assert.equal(isValid("paperCommand",command({type:"settings",settings:{feeSol:-1},revision:0})),false);
  assert.equal(isValid("paperCommand",command({type:"reset",cashSol:1})),false);
});
test("server decisions and normalized intents preserve current buy/partial-sale accounting",async()=>{
  const {freshPaper}=await import("../../src/web/assets/js/paper-wallet.mjs");
  const {buyPaper,sellPaper}=await import("../../src/web/assets/js/trading/paper-pipeline.mjs");
  const paper=freshPaper(),local=structuredClone(paper),market=await fixtureMarket();
  const store={command:async(user,body,fingerprint,fn)=>{assert.equal(user,paper.account.userId);assert.match(fingerprint,/^[a-f0-9]{64}$/);return fn(paper);}};
  const service=createPaperService({store,market}),buy=command({type:"buy",mint:MINTS[0],amount:1,automatic:false,feed:"recent"});
  const bought=await service.command(paper.account.userId,buy),row=market.snapshot().radar.find(r=>r.mint===MINTS[0]);
  const reference=buyPaper({paper:local,row,amount:1,solRate:200,feed:"recent"});
  assert.equal(bought.ok,true);assert.equal(bought.execution.intentId,buy.requestId);
  assert.equal(bought.execution.executionMode,"paper");assert.deepEqual(bought.execution.requested,{value:1,mode:"quote",unit:"USD"});
  assert.equal(paper.cashSol,local.cashSol);assert.equal(paper.holds[MINTS[0]].qty,local.holds[MINTS[0]].qty);
  assert.equal(bought.execution.fees.amount,reference.execution.fees.amount);
  const sold=await service.command(paper.account.userId,command({type:"sell",mint:MINTS[0],dollars:1,automatic:false}));
  sellPaper({paper:local,mint:MINTS[0],dollars:1,solRate:200,mark:{priceUsd:.02,source:"jupiter-v3"},markAt:Date.now()});
  assert.equal(sold.ok,true);assert.equal(paper.cashSol,local.cashSol);assert.equal(paper.realizedUsd,local.realizedUsd);
  for(const k of ["qty","investedUsd","feesUsd"])assert.equal(paper.holds[MINTS[0]][k],local.holds[MINTS[0]][k]);
  assert.equal((await service.command(paper.account.userId,command({type:"sell",mint:MINTS[0],dollars:1,automatic:true}))).ok,false);
  const before=structuredClone(paper);
  await assert.rejects(service.command(paper.account.userId,{...buy,priceUsd:999}),/Invalid paper/);
  assert.deepEqual(paper,before);
});
test("uncertain browser response retains ID across reload; no second command can pass it",async()=>{
  const {createServerPaper}=await import("../../src/web/assets/js/server-paper.mjs");
  const map=new Map(),storage={getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
  const bodies=[];let fail=true;
  const fetchImpl=async(_url,options)=>{bodies.push(JSON.parse(options.body));if(fail)throw Error("lost response");return {ok:true,json:async()=>({ok:true})};};
  const paper={account:{accountId:"fixture"}},first=createServerPaper({storage,fetchImpl});first.attach(paper);
  await assert.rejects(first.send({type:"buy"}),/lost response/);assert.equal(first.pending,true);
  await assert.rejects(first.send({type:"sell"}),/pending/);
  fail=false;const reloaded=createServerPaper({storage,fetchImpl});reloaded.attach(paper);await reloaded.retry();
  assert.deepEqual(bodies[1],bodies[0]);assert.equal(reloaded.pending,false);assert.equal(map.size,0);
});
